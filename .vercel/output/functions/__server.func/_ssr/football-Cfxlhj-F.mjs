function formRate(games, take) {
	if (!games?.length || take <= 0) return null;
	const slice = games.slice(0, take);
	const played = slice.length;
	const gf = slice.reduce((sum, game) => sum + game.gf, 0);
	const ga = slice.reduce((sum, game) => sum + game.ga, 0);
	return {
		played,
		attack: Math.round(gf / played * 100) / 100,
		defense: Math.round(ga / played * 100) / 100
	};
}
/** Apply recent form, then league scale. Equal weights are skipped so same-league math stays put. */
function shapePair(home, away, teams, level, homeSample, awaySample) {
	let nextHome = homeSample ? {
		...home,
		attack: homeSample.attack,
		defense: homeSample.defense
	} : home;
	let nextAway = awaySample ? {
		...away,
		attack: awaySample.attack,
		defense: awaySample.defense
	} : away;
	const homeLeague = rateLeagueOf(home, teams);
	const awayLeague = rateLeagueOf(away, teams);
	const homeWeight = leagueWeight(homeLeague);
	const awayWeight = leagueWeight(awayLeague);
	const leveled = level && homeWeight !== awayWeight;
	if (leveled) {
		nextHome = {
			...nextHome,
			attack: nextHome.attack * homeWeight,
			defense: nextHome.defense / homeWeight
		};
		nextAway = {
			...nextAway,
			attack: nextAway.attack * awayWeight,
			defense: nextAway.defense / awayWeight
		};
	}
	return {
		home: nextHome,
		away: nextAway,
		homeLeague,
		awayLeague,
		homeWeight,
		awayWeight,
		leveled
	};
}
